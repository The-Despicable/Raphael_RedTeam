#!/usr/bin/env bash
# scripts/freeze_images.sh — tag every locally-built Raphael image with a date
# stamp and record the immutable IDs in docker/images.lock.
#
# Why: the anti-forensic toolset and the restored phishing source exist only
# inside these images. A casual `docker compose build` overwrites :latest and
# destroys them. Frozen tags are the rollback.
#
#   ./scripts/freeze_images.sh            # tag with today's date
#   ./scripts/freeze_images.sh 2026-10-28
set -euo pipefail
cd "$(dirname "$0")/.."

STAMP="${1:-$(date +%Y-%m-%d)}"
LOCK="docker/images.lock"
mkdir -p docker

BUILT_IMAGES=$(docker ps -a --format '{{.Image}}' \
  | grep -E '^(raphael|raphael_redteam)' | sort -u)

[ -z "$BUILT_IMAGES" ] && { echo "[freeze] no Raphael images found"; exit 1; }

: > "$LOCK"
{
  echo "# Raphael image freeze — $STAMP"
  echo "# Generated by scripts/freeze_images.sh. Do not edit by hand."
  echo "# Restore:  docker tag <image>:${STAMP} <image>:latest"
} >> "$LOCK"

while read -r img; do
  [ -z "$img" ] && continue
  base="${img%:*}"
  # Skip if the running reference already carries a date tag.
  case "$img" in
    *:"$STAMP") tagged="$img" ;;
    *) docker tag "$img" "${base}:${STAMP}"; tagged="${base}:${STAMP}" ;;
  esac
  id=$(docker image inspect "$tagged" --format '{{.Id}}')
  created=$(docker image inspect "$tagged" --format '{{.Created}}')
  size=$(docker image inspect "$tagged" --format '{{.Size}}')
  printf '%-52s %-20s %12s  %s\n' "$tagged" "${id:7:12}" "$size" "$created" >> "$LOCK"
  echo "[freeze] $img -> $tagged"
done <<< "$BUILT_IMAGES"

echo
echo "[freeze] lock written: $LOCK"
cat "$LOCK"
